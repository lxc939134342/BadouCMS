        'instanceof', 'insteadof', 'interface', 'isset', 'list', 'namespace', 'new', 'or', 'print',
        'private', 'protected', 'public', 'require', 'require_once', 'return', 'static', 'switch',
        'throw', 'trait', 'try', 'unset', 'use', 'var', 'while', 'xor',
    ];
    protected $systemTables = [
        'admin', 'admin_log', 'admin_rule', 'admin_group', 'admin_group_access',
        'config', 'attachment', 'user', 'user_group', 'user_rule', 'user_level', 'user_token',
    ];
